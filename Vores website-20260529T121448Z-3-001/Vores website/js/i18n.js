function getLang() {
    const saved = localStorage.getItem('tekton-lang');
    if (saved === 'en' || saved === 'da') return saved;
    return navigator.language.startsWith('da') ? 'da' : 'en';
}

function applyLang(lang) {
    const t = translations[lang];

    document.documentElement.lang = lang;
    document.title = t['meta.title'];
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', t['meta.desc']);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (t[key] !== undefined) el.textContent = t[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.dataset.i18nHtml;
        if (t[key] !== undefined) el.innerHTML = t[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        if (t[key] !== undefined) el.placeholder = t[key];
    });

    const toggle = document.getElementById('langToggle');
    if (toggle) toggle.textContent = lang === 'en' ? 'DA' : 'EN';

    localStorage.setItem('tekton-lang', lang);
}

const currentLang = getLang();
applyLang(currentLang);

document.getElementById('langToggle').addEventListener('click', () => {
    const next = document.documentElement.lang === 'en' ? 'da' : 'en';
    applyLang(next);
});
